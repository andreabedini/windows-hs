#!/bin/sh
# Write coverage/win32/names.txt: the win32metadata name of every Windows
# function that Hackage's Win32 package imports.
#
# Usage: scripts/win32-surface-names.sh [VERSION]
#
# VERSION is a Win32 package version (default: the one named in the current
# names.txt). The script downloads its source with `cabal get`, collects
# the C names from its `foreign import` declarations, and looks each one up
# in metadata/Windows.Win32.winmd. Names it cannot find are listed on
# stderr and in the file's header: they should all be Win32's own C
# helpers, C runtime functions or macros. Check them before committing.
set -eu
export LC_ALL=C

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/coverage/win32/names.txt"
winmd="$root/metadata/Windows.Win32.winmd"

if [ $# -ge 1 ]; then
  version=$1
else
  version=$(sed -n 's/^# Win32 version: //p' "$out")
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

cd "$root"
cabal build -v0 winmd-dump
dump=$(cabal list-bin winmd-dump)

(cd "$work" && cabal get -v0 "Win32-$version")

# The C name is the last word of the entity string; "dynamic", "wrapper"
# and strings naming only a header have none.
find "$work/Win32-$version" -name '*.hs' -o -name '*.hsc' |
  xargs perl -0777 -ne 'print "$1\n" while /foreign\s+import[^"]*"([^"]*)"/g' |
  awk '{ s = $NF; sub(/^&/, "", s); if (s != "dynamic" && s != "wrapper" && s !~ /\.h$/) print s }' |
  sort -u >"$work/symbols"

# Every function in the metadata, as NAME<TAB>NAMESPACE.
"$dump" "$winmd" | awk 'NF == 2 && $1 ~ /^Windows\./ { print $1 }' |
  while read -r ns; do
    "$dump" "$winmd" "$ns" Apis 2>/dev/null |
      awk -v ns="$ns" '/^  [^ [].*\(/ { s = $0; sub(/\(.*/, "", s); n = split(s, w, " "); print w[n] "\t" ns }'
  done >"$work/index"

awk -F '\t' -v found="$work/found" -v missing="$work/missing" '
  NR == FNR { if ($1 in ns && ns[$1] != $2) dup[$1] = 1; ns[$1] = $2; next }
  $1 in dup { print "ambiguous: " $1 > "/dev/stderr"; bad = 1; next }
  $1 in ns { print ns[$1] "." $1 > found; next }
  { print $1 > missing }
  END { exit bad }
' "$work/index" "$work/symbols"

{
  printf '# The win32metadata name of every Windows function that Hackage'"'"'s Win32\n'
  printf '# package imports. Generated by scripts/win32-surface-names.sh; do not edit.\n'
  printf '# scripts/check-win32-surface.sh generates, compiles and checks them.\n'
  printf '#\n'
  printf '# Win32 version: %s\n' "$version"
  printf '#\n'
  printf '# Imported by Win32 but not Windows API functions in the metadata (its own\n'
  printf '# C helpers, C runtime functions and macros):\n'
  sed 's/^/#   /' "$work/missing"
  printf '\n'
  sort "$work/found"
} >"$out"

printf '%s: %d names, %d not found:\n' "$out" "$(wc -l <"$work/found")" "$(wc -l <"$work/missing")" >&2
sed 's/^/  /' "$work/missing" >&2
