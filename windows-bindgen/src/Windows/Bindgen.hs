-- | Generate Haskell bindings to the Windows API from win32metadata.
module Windows.Bindgen
  ( Config (..)
  , defaultConfig
  , Output (..)
  , bindgen
  , cLayoutChecks
  , parseNames
  ) where

import Data.Text (Text)
import Data.Text qualified as T
import WinMD
import Windows.Bindgen.Emit
import Windows.Bindgen.Layout
import Windows.Bindgen.Model

-- | The module @Windows.Win32@ with the standard header.
defaultConfig :: Config
defaultConfig =
  Config
    { cfgModuleName = "Windows.Win32"
    , cfgHeader = ["Generated by windows-bindgen. Do not edit."]
    }

-- | Generate one module containing the named items and everything they
-- depend on. Names that match nothing are errors.
bindgen :: Config -> Database -> [Text] -> Either [String] Output
bindgen cfg db names = generate cfg <$> select db names

-- | Parse a names file: one name per line, with @#@ starting a comment.
parseNames :: Text -> [Text]
parseNames contents =
  [n | l <- T.lines contents, let n = T.strip (T.takeWhile (/= '#') l), not (T.null n)]

-- | A C file that checks, at compile time, that the layouts the generator
-- computed match the Windows headers. Compile it with a Windows C compiler
-- (for example @x86_64-w64-mingw32-gcc -c@).
--
-- Only top-level types are checked, by their metadata names. Fields named
-- @Anonymous*@ stand for C anonymous unions and structs, which have no
-- name to take the offset of, so they are skipped.
cLayoutChecks :: Output -> Text
cLayoutChecks out =
  T.unlines $
    [ "/* Generated by windows-bindgen: layout checks. */"
    , "#include <windows.h>"
    , "#include <stddef.h>"
    , ""
    ]
      ++ concatMap check (outStructs out)
  where
    check (t, _)
      | Just _ <- typeDefEnclosingType t = []
      | otherwise = case defLayout t of
          Left _ -> []
          Right (Layout size align) ->
            let c = typeDefName t
             in [assert ("sizeof(" <> c <> ") == " <> tshow size) (c <> " size")]
                  ++ [ assert ("_Alignof(" <> c <> ") == " <> tshow align) (c <> " alignment")
                     | classify t /= KNativeTypedef
                     ]
                  ++ [ assert ("offsetof(" <> c <> ", " <> fieldName f <> ") == " <> tshow off) (c <> "." <> fieldName f)
                     | classify t == KStruct
                     , Right fields <- [structFields t]
                     , (f, off, _) <- fields
                     , not ("Anonymous" `T.isPrefixOf` fieldName f)
                     ]
    assert cond msg = "_Static_assert(" <> cond <> ", \"" <> msg <> "\");"
    tshow = T.pack . show
